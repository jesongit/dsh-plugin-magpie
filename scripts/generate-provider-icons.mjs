// Regenerates src/client/provider-icons.ts from a Magpie checkout's icon
// directory, so any provider whose logo Magpie already ships works in the
// plugin pill without further code changes. Run once per Magpie update:
//   node scripts/generate-provider-icons.mjs <path-to-magpie-checkout>
// Output is committed; the build never depends on the checkout.
import { readdir, readFile, writeFile } from 'node:fs/promises'
import { extname, join } from 'node:path'

const checkout = process.argv[2]
if (!checkout) throw new Error('usage: node scripts/generate-provider-icons.mjs <magpie-checkout>')
const directory = join(checkout, 'internal', 'gui', 'assets', 'icons')
const files = (await readdir(directory, { withFileTypes: true }))
  .filter(entry => entry.isFile() && ['.svg', '.png'].includes(extname(entry.name).toLowerCase()))
  .map(entry => entry.name)
  .sort()
const lines = [
  '// Provider logos embedded from the Magpie checkout (internal/gui/assets/icons),',
  '// MIT Copyright (c) 2026 yetone; full license in THIRD-PARTY-NOTICES.',
  '// Generated by scripts/generate-provider-icons.mjs; regenerate after Magpie adds logos.',
  'export const PROVIDER_ICONS: Readonly<Record<string, string | undefined>> = {'
]
for (const name of files) {
  const key = name.slice(0, -extname(name).length)
  const mime = extname(name).toLowerCase() === '.png' ? 'image/png' : 'image/svg+xml'
  const body = await readFile(join(directory, name))
  lines.push(`  ${JSON.stringify(key)}: 'data:${mime};base64,${body.toString('base64')}',`)
}
lines.push('}')
lines.push('// Lookups try <id>, <id>-color, the id without a -cn suffix, then app-<id>;')
lines.push('// anything unmatched falls back to the monochrome magpie mark.')
await writeFile(new URL('../src/client/provider-icons.ts', import.meta.url), lines.join('\n') + '\n')
console.log(`embedded ${files.length} icons from ${directory}`)
